def build():
    rng = random.Random(SEED)
    out = {}
    for key, (title, raw) in EXAMS.items():
        # Deal the correct positions evenly, then shuffle the deal: a plain
        # per-item shuffle drifted to 40% on one letter in two exams.
        n_mc = sum(1 for it in raw if it["_t"] == "mc")
        positions = ([0, 1, 2, 3] * (n_mc // 4 + 1))[:n_mc]
        rng.shuffle(positions)
        items = []
        for it in raw:
            if it["_t"] == "mc":
                opts = list(it["distractors"])
                rng.shuffle(opts)
                opts.insert(positions.pop(), it["correct_text"])
                items.append({"type": "mc", "topic": it["topic"], "q": it["q"],
                              "options": opts, "correct": opts.index(it["correct_text"]),
                              "exp": it["exp"]})
            else:
                items.append({"type": "fill", "topic": it["topic"], "q": it["q"],
                              "answer": it["answer"], "exp": it["exp"]})
        out[key] = {"title": title, "items": items}
    return out


def to_js(exams):
    j = lambda v: json.dumps(v, ensure_ascii=False)
    lines = ["// מבחני בית שני, התקופה הרומית, התקופה הביזנטית וארכיאולוגיה קלאסית.",
             "// נוצר אוטומטית ע\"י tools/build_temple_exams.py — לערוך שם, לא כאן.",
             "const TEMPLE_EXAMS = {"]
    for key, exam in exams.items():
        lines.append(f"  {key}: {{")
        lines.append(f"    title: {j(exam['title'])},")
        lines.append("    items: [")
        for it in exam["items"]:
            if it["type"] == "mc":
                lines.append(f"      {{ type: \"mc\", topic: {j(it['topic'])}, q: {j(it['q'])}, "
                             f"options: {j(it['options'])}, correct: {it['correct']}, exp: {j(it['exp'])} }},")
            else:
                lines.append(f"      {{ type: \"fill\", topic: {j(it['topic'])}, q: {j(it['q'])}, "
                             f"answer: {j(it['answer'])}, exp: {j(it['exp'])} }},")
        lines.append("    ]")
        lines.append("  },")
    lines.append("};")
    return "\n".join(lines) + "\n"


EXTRACT_JS = """
const fs = require('fs');
let src = fs.readFileSync(process.argv[2], 'utf8');
const open = src.indexOf('<script');
src = src.slice(src.indexOf('>', open) + 1, src.indexOf('</script>', open));
const cut = src.search(/\\n\\s*(document|window|const state|let state)\\b/);
const data = cut > 0 ? src.slice(0, cut) : src;
const read = new Function(data + "\\nreturn {EXAMS, FOCUS_EXAMS, TOPIC_EXAMS};");
process.stdout.write(JSON.stringify(read()));
"""


def existing_corpus():
    """Every exam already on the site, for cross-exam duplicate detection."""
    with tempfile.NamedTemporaryFile("w", suffix=".js", delete=False) as f:
        f.write(EXTRACT_JS)
    out = subprocess.run(["node", f.name, str(HTML)], capture_output=True, text=True, check=True)
    src = json.loads(out.stdout)
    corpus = {}
    for name, coll in src.items():
        for k, ex in coll.items():
            items = ex.get("items") or (
                [dict(it, type="mc") for it in ex.get("mc", [])]
                + [{"type": "fill", "topic": it.get("topic", ""), "q": it["q"],
                    "answer": it.get("answer", "-"), "exp": it.get("exp", "-")}
                   for it in ex.get("open", [])])
            corpus[f"{name}-{k}"] = {"title": ex.get("title", ""), "items": items}
    return corpus


def splice(js):
    html = HTML.read_text()
    if "const TEMPLE_EXAMS = {" in html:
        start = html.index("// מבחני בית שני, התקופה הרומית")
        end = html.index("const TOPIC_EXAMS = {")
        html = html[:start] + html[end:]
    end = html.index("const TOPIC_EXAMS = {")
    html = html[:end] + js + "\n" + html[end:]
    HTML.write_text(html)


def main():
    exams = build()
    corpus = existing_corpus()  # before splicing, so the new set isn't read twice
    (ROOT / "tools/temple_exams.json").write_text(json.dumps(exams, ensure_ascii=False, indent=1))
    corpus.update({f"TEMPLE-{k}": v for k, v in exams.items()})
    (ROOT / "tools/all_exams.json").write_text(json.dumps(corpus, ensure_ascii=False))  # scratch, for the cross-corpus duplicate check
    splice(to_js(exams))
    for k, ex in exams.items():
        fills = sum(1 for it in ex["items"] if it["type"] == "fill")
        print(f"{k}: {len(ex['items'])} items, {fills} fill-in — {ex['title']}")


if __name__ == "__main__":
    main()
